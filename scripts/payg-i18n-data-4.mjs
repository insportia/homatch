// things like "Base — POTENTIAL" and "Multiplier — COGS" in untranslated
// English. An owner deciding how many free credits to give away should not
// have to know what a basis point is.
//
// So each control is named after the DECISION, and the sentence underneath
// says what changes when you move it -- including, where it matters, what
// does NOT change. "Changing this does not touch balances anyone already
// holds" is the sentence that stops somebody being afraid of the first field.

