#!/usr/bin/env node
/*
 * THE DENO COPY TABLE FOR TRANSACTIONAL NOTIFICATIONS.
 *
 * Edge functions cannot import src/i18n/translations.ts (151k lines, and the browser owns it),
 * so the sentences the email leg, the stored notification title and the unsubscribe page need
 * are generated from the bundle into
 *   supabase/functions/_shared/notificationCopy.generated.ts
 * the same way scripts/sw-push-copy.mjs feeds the service worker. Deterministic: keys sorted,
 * languages in a fixed order. A test fails when the file and the bundle disagree.
 *
 *   node scripts/saas-notify-copy.mjs          write the file
 *   node scripts/saas-notify-copy.mjs --check  exit 1 when it is stale
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SAAS_NOTIFY_STRINGS } from './saas-notify-i18n-data.mjs';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
export const COPY_FILE = path.join(root, 'supabase', 'functions', '_shared', 'notificationCopy.generated.ts');
/* Georgian first: it is the default language. */
export const COPY_LANGS = ['ka', 'en', 'ru', 'tr', 'ar', 'he'];
/* Every customer-facing key of this workstream; the admin_ keys stay in the browser. */
export const COPY_KEYS = Object.keys(SAAS_NOTIFY_STRINGS).filter((k) => k.startsWith('ntf_')).sort();

export async function copySource() {
  const { translations } = await import('../src/i18n/translations.ts');
  const table = {};
  for (const lang of COPY_LANGS) {
    table[lang] = {};
    for (const key of COPY_KEYS) {
      const v = translations[lang]?.[key];
      if (typeof v !== 'string' || !v.trim()) throw new Error(`missing ${key} for ${lang}`);
      table[lang][key] = v;
    }
  }
  return [
    '// GENERATED by scripts/saas-notify-copy.mjs from src/i18n/translations.ts. Do not edit by hand.',
    '// Source strings: scripts/saas-notify-i18n-data.mjs (apply with scripts/saas-notify-i18n-apply.mjs).',
    '',
    `export const NOTIFICATION_COPY_LANGS = ${JSON.stringify(COPY_LANGS)} as const;`,
    'export type NotificationCopyLang = typeof NOTIFICATION_COPY_LANGS[number];',
    `export const NOTIFICATION_COPY: Record<NotificationCopyLang, Record<string, string>> = ${JSON.stringify(table, null, 2)};`,
    '',
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = await copySource();
  const prev = fs.existsSync(COPY_FILE) ? fs.readFileSync(COPY_FILE, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (prev !== next) { console.error('[saas-notify-copy] stale: run node scripts/saas-notify-copy.mjs'); process.exit(1); }
    console.log('[saas-notify-copy] up to date');
  } else {
    if (prev !== next) fs.writeFileSync(COPY_FILE, next);
    console.log(prev === next ? '[saas-notify-copy] unchanged' : '[saas-notify-copy] written');
  }
}
