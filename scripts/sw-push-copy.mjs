#!/usr/bin/env node
/*
 * PUSH NOTIFICATIONS IN THE LANGUAGE THE SITE IS OPEN IN (owner 2026-10-24).
 *
 * A push is drawn by the service worker, which has no access to the page's
 * translations, so the server's stored English reached the phone. The page
 * now tells the worker its language (src/lib/swLanguage.ts) and the worker
 * draws typed notifications from this table — the same keys the in-app
 * Notification Center uses (src/components/notifications/presentation.tsx).
 *
 * Generated from src/i18n/translations.ts into the marked block of
 * src/serviceWorker/sw.source.js:  node scripts/sw-push-copy.mjs
 * A test fails when the block and the bundle disagree.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SW_FILE = path.join(root, 'src', 'serviceWorker', 'sw.source.js');
export const PUSH_TYPES = {
  VERIFY_COMPLETE: 'notif_verify_complete',
  LOW_CREDITS: 'notif_low_credits',
  RESEARCH_PRODUCT_PURCHASED: 'notif_research_purchased',
  PROPERTY_ACTION_REQUIRED: 'notif_property_action',
  SEARCH_COMPLETE: 'notif_search_complete',
  DOCUMENT_ANALYZED: 'notif_document_analyzed',
};
export const LANGS = ['en', 'ka', 'ru', 'tr', 'ar', 'he'];
export const BEGIN = '/* <push-copy> generated by scripts/sw-push-copy.mjs — do not edit by hand */';
export const END = '/* </push-copy> */';

export async function pushCopyBlock() {
  const { translations } = await import('../src/i18n/translations.ts');
  const table = {};
  for (const [type, key] of Object.entries(PUSH_TYPES)) {
    table[type] = {};
    for (const lang of LANGS) {
      const title = translations[lang]?.[`${key}_title`];
      const body = translations[lang]?.[`${key}_body`];
      if (!title || !body) throw new Error(`missing ${key}_title/_body for ${lang}`);
      table[type][lang] = [title, body];
    }
  }
  return `${BEGIN}\nconst PUSH_COPY = ${JSON.stringify(table, null, 2)};\n${END}`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const src = fs.readFileSync(SW_FILE, 'utf8');
  const a = src.indexOf(BEGIN);
  const b = src.indexOf(END);
  if (a < 0 || b < a) throw new Error('push-copy markers not found in sw.source.js');
  const next = src.slice(0, a) + (await pushCopyBlock()) + src.slice(b + END.length);
  fs.writeFileSync(SW_FILE, next);
  console.log(next === src ? '[sw-push-copy] unchanged' : '[sw-push-copy] written');
}
