import { useEffect, useRef, useState } from 'react';
import * as THREE from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import { DRACOLoader } from 'three/examples/jsm/loaders/DRACOLoader.js';
import type { HomiState } from './homiStates';
import { actPose, startAct, type ActClock, type HomiPose, REST } from './homiActs';

/*
 * HOMI, live 3D — the approved HOMI master (homatch-video Blender file),
 * exported to public/models/homi/homi.glb with pivots for the head, eyes,
 * brows, mouth and both arms (scripts/homi/export-glb.py).
 *
 * Every movement and expression comes from homiActs.ts: several different
 * acts per state, picked at random and rotated, each driving body AND face.
 * Natural blinking runs underneath. Nothing is generated by a model and
 * nothing claims to show what an AI is "thinking".
 *
 * Cost control: three.js and the model load only when needed; rendering runs
 * only while on screen and the tab is visible; 30 fps on touch devices; a
 * single still frame per state under reduced motion. Failure → `onFail`.
 */

/** The homepage's earlier vocabulary, still accepted. */
export type HomiGesture = 'idle' | 'greeting' | 'pointing' | 'explaining' | 'happy';

export interface HomiStage3DProps {
  gesture: HomiGesture | HomiState;
  /** Where to point, in the stage's own horizontal space: -1 left … 1 right. */
  pointTo?: number;
  /** An element HOMI should look and point at (the tile in focus). Followed live, also while scrolling. */
  target?: HTMLElement | null;
  /** 'full' shows all of HOMI; 'upper' frames head, torso and arms (for small boxes). */
  framing?: 'full' | 'upper';
  onFail: () => void;
  onReady?: () => void;
  className?: string;
}

const MODEL_URL = '/models/homi/homi.glb';
const PART = /^HOMI_(HEAD|EYE_L|EYE_R|BROW_L|BROW_R|MOUTH|ARM_L|ARM_R|FOREARM_L|FOREARM_R)$/;

function reducedMotion(): boolean {
  try { return window.matchMedia('(prefers-reduced-motion: reduce)').matches; } catch { return false; }
}

const damp = (a: number, b: number, k: number, dt: number) => a + (b - a) * (1 - Math.exp(-k * dt));

export default function HomiStage3D({ gesture, pointTo = 1, target = null, framing = 'full', onFail, onReady, className }: HomiStage3DProps) {
  const host = useRef<HTMLDivElement>(null);
  const stateRef = useRef<{ state: HomiState; point: number }>({ state: gesture, point: pointTo });
  const targetRef = useRef<HTMLElement | null>(target);
  const [loaded, setLoaded] = useState(false);

  useEffect(() => { targetRef.current = target; }, [target]);
  useEffect(() => { stateRef.current = { state: gesture, point: pointTo }; }, [gesture, pointTo]);

  useEffect(() => {
    const el = host.current;
    if (!el) return;
    let disposed = false;
    let renderer: THREE.WebGLRenderer;
    try {
      renderer = new THREE.WebGLRenderer({ antialias: true, alpha: true, powerPreference: 'low-power' });
    } catch {
      onFail();
      return;
    }
    const still = reducedMotion();
    const coarse = window.matchMedia?.('(pointer: coarse)').matches ?? false;
    renderer.setPixelRatio(Math.min(window.devicePixelRatio || 1, coarse ? 1.5 : 1.75));
    renderer.outputColorSpace = THREE.SRGBColorSpace;
    renderer.toneMapping = THREE.ACESFilmicToneMapping;
    renderer.toneMappingExposure = 1.05;
    renderer.domElement.style.width = '100%';
    renderer.domElement.style.height = '100%';
    renderer.domElement.setAttribute('aria-hidden', 'true');
    el.appendChild(renderer.domElement);

    const scene = new THREE.Scene();
    const camera = new THREE.PerspectiveCamera(26, 1, 0.1, 50);
    if (framing === 'upper') { camera.position.set(0, 1.25, 3.3); camera.lookAt(0, 1.15, 0); }
    else { camera.position.set(0, 0.92, 4.0); camera.lookAt(0, 0.84, 0); }

    scene.add(new THREE.HemisphereLight(0xf3f5f8, 0x1a1f2b, 1.25));
    const key = new THREE.DirectionalLight(0xffffff, 2.4);
    key.position.set(1.6, 2.6, 3.2);
    scene.add(key);
    const rim = new THREE.DirectionalLight(0xf5b445, 1.6); // the brand's gold, from behind
    rim.position.set(-2.2, 1.8, -2.4);
    scene.add(rim);

    const resize = () => {
      const w = el.clientWidth || 1, h = el.clientHeight || 1;
      renderer.setSize(w, h, false);
      camera.aspect = w / h;
      camera.updateProjectionMatrix();
    };
    resize();
    const ro = typeof ResizeObserver !== 'undefined' ? new ResizeObserver(resize) : null;
    ro?.observe(el);

    const parts: Record<string, THREE.Object3D | undefined> = {};
    const rest = new Map<THREE.Object3D, { r: THREE.Euler; p: THREE.Vector3; s: THREE.Vector3 }>();
    let root: THREE.Object3D | null = null;

    const loader = new GLTFLoader();
    const draco = new DRACOLoader();
    draco.setDecoderPath('/three/draco/');
    loader.setDRACOLoader(draco);
    loader.loadAsync(MODEL_URL).then((gltf) => {
      if (disposed) return;
      root = gltf.scene;
      root.traverse((o) => {
        if (PART.test(o.name)) {
          parts[o.name] = o;
          rest.set(o, { r: o.rotation.clone(), p: o.position.clone(), s: o.scale.clone() });
        }
        const mesh = o as THREE.Mesh;
        if (mesh.isMesh) {
          const mat = mesh.material as THREE.MeshStandardMaterial;
          /* The LED and eye materials glow on the visor; give them the
             emissive the renderer needs to read them as light. */
          if (mat && /LED|Eye_Iris|Ear_Glass/i.test(mat.name)) {
            mat.emissive = new THREE.Color(0x4fb2ff);
            mat.emissiveIntensity = /Iris/.test(mat.name) ? 0.9 : 1.6;
          }
        }
      });
      scene.add(root);
      draco.dispose();
      setLoaded(true);
      onReady?.();
      renderOnce();
    }).catch(() => { if (!disposed) onFail(); });

    /*
     * WHAT HOMI LOOKS AT, in screen coordinates. A finger on a phone wins for
     * a moment after it moves, then the element in focus, then the mouse.
     */
    const mouse = { cx: 0, cy: 0, active: false };
    const touch = { cx: 0, cy: 0, at: 0 };
    const onMouse = (e: PointerEvent) => {
      if (e.pointerType === 'touch') return;
      mouse.cx = e.clientX; mouse.cy = e.clientY; mouse.active = true;
    };
    const onTouch = (e: TouchEvent) => {
      const p = e.touches[0];
      if (!p) return;
      touch.cx = p.clientX; touch.cy = p.clientY; touch.at = performance.now();
    };
    if (!still) {
      window.addEventListener('pointermove', onMouse, { passive: true });
      window.addEventListener('touchstart', onTouch, { passive: true });
      window.addEventListener('touchmove', onTouch, { passive: true });
    }
    const pointer = { x: 0, y: 0, active: false, dx: 0, dyUp: 0, hasAim: false };
    const aim = () => {
      const r = el.getBoundingClientRect();
      let cx: number | null = null, cy: number | null = null;
      const tgt = targetRef.current;
      if (performance.now() - touch.at < 1800) { cx = touch.cx; cy = touch.cy; }
      else if (tgt && tgt.isConnected) { const b = tgt.getBoundingClientRect(); cx = b.left + b.width / 2; cy = b.top + b.height / 2; }
      else if (mouse.active) { cx = mouse.cx; cy = mouse.cy; }
      if (cx === null || cy === null) { pointer.active = false; pointer.hasAim = false; return; }
      const ox = r.left + r.width / 2, oy = r.top + r.height * 0.3;
      pointer.x = Math.max(-1, Math.min(1, (cx - ox) / (window.innerWidth / 2)));
      pointer.y = Math.max(-1, Math.min(1, (cy - oy) / (window.innerHeight / 2)));
      pointer.dx = cx - ox; pointer.dyUp = oy + r.height * 0.12 - cy;
      pointer.active = true; pointer.hasAim = true;
    };

    let clock: ActClock = startAct(stateRef.current.state, performance.now());
    /* Natural blinking: every 2.4–5 s, 130 ms, now and then a double blink. */
    let nextBlink = performance.now() + 1800;
    let blinkUntil = 0;
    const cur: HomiPose = { ...REST };

    const apply = (name: string, f: (o: THREE.Object3D, base: { r: THREE.Euler; p: THREE.Vector3; s: THREE.Vector3 }) => void) => {
      const o = parts[name]; const base = o && rest.get(o);
      if (o && base) f(o, base);
    };

    const pose = (now: number, dt: number) => {
      const { state, point } = stateRef.current;
      if (state !== clock.state || now >= clock.nextSwitchAt) clock = startAct(state, now, clock);
      const want = actPose(clock, now, still);

      /* Gaze follows the pointer / focus for calm states, and aims the arm when pointing. */
      aim();
      if (pointer.active && (state === 'idle' || state === 'pointing' || state === 'listening')) {
        want.headY = pointer.x * 0.35; want.headX += pointer.y * 0.1; want.eyeX = pointer.x; want.eyeY = pointer.y;
      }
      if (state === 'pointing') {
        const right = pointer.hasAim ? pointer.dx >= 0 : point >= 0;
        const angle = pointer.hasAim ? Math.atan2(Math.abs(pointer.dx), -pointer.dyUp) : Math.PI * 0.43;
        const a = Math.max(0.35, Math.min(2.5, angle));
        if (right) { want.armL = a; want.foreL = 0.12; if (!pointer.hasAim) { want.headY = 0.35; want.eyeX = 1; } }
        else { want.armR = -a; want.foreR = -0.12; if (!pointer.hasAim) { want.headY = -0.35; want.eyeX = -1; } }
      }

      if (!still && now >= nextBlink) {
        blinkUntil = now + 130;
        nextBlink = now + (Math.random() < 0.2 ? 260 : 2400 + Math.random() * 2600);
      }
      const blink = now < blinkUntil ? 1 : 0;

      const k = still ? 1000 : 7;
      for (const key of Object.keys(cur) as Array<keyof HomiPose>) {
        const speed = key === 'turn' || key === 'lift' ? k * 1.4 : key.startsWith('eye') || key === 'squint' ? k * 1.8 : k;
        cur[key] = damp(cur[key], want[key], speed, dt);
      }
      const breath = still ? 0 : Math.sin(now / 1000 * 1.7);
      const squint = Math.min(1, Math.max(cur.squint, blink));

      apply('HOMI_HEAD', (o, b) => { o.rotation.set(b.r.x + cur.headX, b.r.y + cur.headY, b.r.z + cur.headZ); });
      for (const side of ['EYE_L', 'EYE_R']) {
        apply(`HOMI_${side}`, (o, b) => {
          o.position.set(b.p.x + cur.eyeX * 0.012, b.p.y - cur.eyeY * 0.008, b.p.z);
          const open = Math.max(0.08, 1 - squint * 0.88);
          o.scale.set(b.s.x * cur.eyeScale, b.s.y * cur.eyeScale * open, b.s.z * cur.eyeScale);
        });
      }
      for (const [side, sign] of [['BROW_L', 1], ['BROW_R', -1]] as const) {
        apply(`HOMI_${side}`, (o, b) => {
          const asym = side === 'BROW_L' ? cur.browAsym : -cur.browAsym * 0.3;
          o.position.set(b.p.x, b.p.y + (cur.browUp + asym) * 0.012, b.p.z);
          o.rotation.set(b.r.x, b.r.y, b.r.z + sign * cur.browTilt * 0.35);
        });
      }
      apply('HOMI_MOUTH', (o, b) => { o.scale.set(b.s.x * cur.mouthW, b.s.y * cur.mouthH, b.s.z); });
      apply('HOMI_ARM_R', (o, b) => { o.rotation.set(b.r.x - cur.fwdR, b.r.y, b.r.z + cur.armR); });
      apply('HOMI_FOREARM_R', (o, b) => { o.rotation.set(b.r.x - cur.foreFwdR, b.r.y, b.r.z + cur.foreR); });
      apply('HOMI_ARM_L', (o, b) => { o.rotation.set(b.r.x - cur.fwdL, b.r.y, b.r.z + cur.armL); });
      apply('HOMI_FOREARM_L', (o, b) => { o.rotation.set(b.r.x - cur.foreFwdL, b.r.y, b.r.z + cur.foreL); });
      if (root) {
        root.position.y = breath * 0.008 + cur.lift;
        root.rotation.set(cur.lean, cur.turn, 0);
      }
    };

    let raf = 0, last = performance.now(), lastFrame = 0;
    let visible = true;
    const minFrame = coarse ? 33 : 16;
    const renderOnce = () => { pose(performance.now(), 1); renderer.render(scene, camera); };
    const tick = (now: number) => {
      raf = requestAnimationFrame(tick);
      if (!visible || document.hidden || !root || now - lastFrame < minFrame) return;
      const dt = Math.min(0.1, (now - last) / 1000);
      last = now; lastFrame = now;
      pose(now, dt);
      renderer.render(scene, camera);
    };
    const io = typeof IntersectionObserver !== 'undefined'
      ? new IntersectionObserver((entries) => { visible = entries.some((e) => e.isIntersecting); })
      : null;
    io?.observe(el);
    if (!still) raf = requestAnimationFrame(tick);
    /* Under reduced motion, re-render once when the state changes. */
    let lastState = stateRef.current.state;
    const stillTimer = still ? window.setInterval(() => {
      if (root && stateRef.current.state !== lastState) { lastState = stateRef.current.state; renderOnce(); }
    }, 300) : 0;

    return () => {
      disposed = true;
      cancelAnimationFrame(raf);
      if (stillTimer) window.clearInterval(stillTimer);
      io?.disconnect();
      ro?.disconnect();
      window.removeEventListener('pointermove', onMouse);
      window.removeEventListener('touchstart', onTouch);
      window.removeEventListener('touchmove', onTouch);
      scene.traverse((o) => {
        const m = o as THREE.Mesh;
        if (m.isMesh) {
          m.geometry?.dispose();
          const mats = Array.isArray(m.material) ? m.material : [m.material];
          mats.forEach((mat) => mat?.dispose());
        }
      });
      renderer.dispose();
      renderer.domElement.remove();
    };
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [framing]);

  return <div ref={host} className={className} data-homi-3d={loaded ? 'ready' : 'loading'} data-homi-act={gesture} />;
}
