-- HOMATCH Voice AI — the domain intelligence layer.
--
-- WHY A TABLE AND NOT A CONSTANT FILE
--
-- Homatch's voice vocabulary is over a thousand terms and it is not static:
-- districts get built, developers get founded, a tenant has words for its own
-- projects that nobody else needs. A constant in the bundle cannot be edited
-- by the person who knows the market, cannot be scoped to one tenant, and
-- ships to every browser whether or not anybody speaks.
--
-- It is also emphatically NOT a payload. The realtime transcriber takes a few
-- dozen terms; this is where the other thousand live so that intent, entity
-- and pronunciation work can use them without any of it being sent anywhere.
--
-- WHAT THE IDENTITY COLUMNS MEAN
--
-- owner_id is the AUTH uid, matching comm_agents exactly. That is deliberate
-- and it is the one thing this migration must not get wrong: an earlier
-- Communications release wrote policies against public.users.id while the
-- foreign keys pointed at auth.users.id, and the result was a set of tables
-- that could be neither read nor written by the people who owned the rows.

-- ── The corpus ───────────────────────────────────────────────────────────────

create table if not exists public.voice_vocabulary_terms (
  id uuid primary key default gen_random_uuid(),
  term text not null,
  -- Case- and punctuation-folded, for deduplication and search. Generated
  -- rather than trusted, so an import cannot disagree with the selector.
  normalized_term text generated always as (lower(btrim(term))) stored,
  language_hint text,
  -- TEXT, not an enum. The seed categories are a starting point and an admin
  -- adding "developer_projects" must not need a migration to do it.
  category text not null,
  scope text not null default 'GLOBAL'
    check (scope in ('GLOBAL','TENANT','AGENT','PROPERTY','PROJECT')),
  owner_id uuid references auth.users(id) on delete cascade,
  agent_id uuid references public.comm_agents(id) on delete cascade,
  property_id uuid,
  priority smallint not null default 50 check (priority between 0 and 100),
  enabled boolean not null default true,
  -- False for anything that must never bias a realtime transcriber: the 325
  -- intent phrases are semantic test material, and the abuse lexicon becomes
  -- eligible only inside a session that has already contained abuse.
  provider_eligible boolean not null default true,
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- A GLOBAL term belongs to nobody; a TENANT term must belong to somebody.
  constraint voice_vocabulary_scope_owner check (
    (scope = 'GLOBAL' and owner_id is null)
    or (scope <> 'GLOBAL' and owner_id is not null)
  )
);

create unique index if not exists voice_vocabulary_terms_unique
  on public.voice_vocabulary_terms (category, normalized_term, coalesce(owner_id, '00000000-0000-0000-0000-000000000000'::uuid));
create index if not exists voice_vocabulary_terms_lookup
  on public.voice_vocabulary_terms (enabled, provider_eligible, language_hint, priority desc);
create index if not exists voice_vocabulary_terms_owner
  on public.voice_vocabulary_terms (owner_id) where owner_id is not null;
create index if not exists voice_vocabulary_terms_search
  on public.voice_vocabulary_terms using gin (to_tsvector('simple', term));

-- ── Pronunciation, which is a different problem from recognition ────────────
--
-- Knowing that somebody SAID "Homatch" and knowing how Homatch should SAY
-- "Homatch" are unrelated. One is a keyterm, the other is a rule applied to
-- synthesis, and solving the second with string replacement on the first is
-- how a brand becomes "Ho match" in every sentence it appears in.

create table if not exists public.voice_pronunciation_rules (
  id uuid primary key default gen_random_uuid(),
  term text not null,
  language text,
  provider text not null default 'ELEVENLABS',
  -- Which models this rule is known to work with. Phonemes are not universally
  -- supported and a silently ignored rule is worse than a refused one: the
  -- owner approves audio that customers will never hear.
  model_compatibility text[] not null default '{}',
  method text not null check (method in ('alias','phoneme')),
  value text not null,
  alphabet text check (alphabet in ('ipa','cmu-arpabet')),
  scope text not null default 'GLOBAL'
    check (scope in ('GLOBAL','TENANT','AGENT')),
  owner_id uuid references auth.users(id) on delete cascade,
  agent_id uuid references public.comm_agents(id) on delete cascade,
  priority smallint not null default 50 check (priority between 0 and 100),
  enabled boolean not null default false,
  -- A rule is not live until somebody has heard it. The Admin preview
  -- generates real audio and this records who accepted it.
  approved_by uuid references auth.users(id) on delete set null,
  approved_at timestamptz,
  -- The provider-side dictionary this rule has been published into.
  provider_dictionary_id text,
  provider_version_id text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint voice_pronunciation_scope_owner check (
    (scope = 'GLOBAL' and owner_id is null)
    or (scope <> 'GLOBAL' and owner_id is not null)
  ),
  -- Enabling a rule nobody has listened to is the failure mode this prevents.
  constraint voice_pronunciation_approved_before_enabled check (
    enabled = false or approved_at is not null
  )
);

create index if not exists voice_pronunciation_rules_lookup
  on public.voice_pronunciation_rules (enabled, provider, language, priority desc);

-- ── The voice library, as the provider actually reports it ──────────────────

create table if not exists public.voice_library_voices (
  id uuid primary key default gen_random_uuid(),
  provider text not null default 'ELEVENLABS',
  provider_voice_id text not null,
  name text not null,
  category text,
  description text,
  preview_url text,
  -- Only metadata the provider returned. Nothing here is invented, because a
  -- voice described as speaking a language it cannot is worse than one with
  -- no description at all.
  labels jsonb not null default '{}'::jsonb,
  languages text[] not null default '{}',
  -- Admin decides what customers may choose from.
  enabled boolean not null default false,
  recommended boolean not null default false,
  is_default boolean not null default false,
  sort_order smallint not null default 100,
  last_synced_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (provider, provider_voice_id)
);

create index if not exists voice_library_voices_enabled
  on public.voice_library_voices (provider, enabled, sort_order);

-- Exactly one default, enforced by the database rather than by hope.
create unique index if not exists voice_library_single_default
  on public.voice_library_voices (provider) where is_default;

-- ── Personality, as configuration rather than as a prompt somebody edits ────

create table if not exists public.voice_personality_profiles (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  scope text not null default 'GLOBAL' check (scope in ('GLOBAL','TENANT','AGENT')),
  owner_id uuid references auth.users(id) on delete cascade,
  agent_id uuid references public.comm_agents(id) on delete cascade,
  -- 0-100 dials. Only the ones the selected provider and model support are
  -- ever shown; the rest are stored and ignored rather than pretended about.
  brevity smallint not null default 80 check (brevity between 0 and 100),
  warmth smallint not null default 70 check (warmth between 0 and 100),
  formality smallint not null default 40 check (formality between 0 and 100),
  sales_intensity smallint not null default 20 check (sales_intensity between 0 and 100),
  proactivity smallint not null default 55 check (proactivity between 0 and 100),
  confirmation smallint not null default 40 check (confirmation between 0 and 100),
  interruption_sensitivity smallint not null default 60 check (interruption_sensitivity between 0 and 100),
  speaking_rate numeric(4,2) not null default 1.00 check (speaking_rate between 0.50 and 2.00),
  -- Provider voice settings, stored only when the model honours them.
  stability numeric(4,3) check (stability between 0 and 1),
  similarity_boost numeric(4,3) check (similarity_boost between 0 and 1),
  style numeric(4,3) check (style between 0 and 1),
  use_speaker_boost boolean,
  -- Extra instruction an admin wants every spoken turn to carry.
  extra_instructions text,
  is_default boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint voice_personality_scope_owner check (
    (scope = 'GLOBAL' and owner_id is null)
    or (scope <> 'GLOBAL' and owner_id is not null)
  )
);

create unique index if not exists voice_personality_single_default
  on public.voice_personality_profiles (scope) where is_default and scope = 'GLOBAL';

-- ── What was spent, and what was sent ───────────────────────────────────────
--
-- Provider cost and customer price are different numbers and this table holds
-- only the first. Nothing here may be read as retail: §R is explicit that a
-- provider cost moving must not move what a customer pays.

create table if not exists public.voice_usage_events (
  id uuid primary key default gen_random_uuid(),
  occurred_at timestamptz not null default now(),
  owner_id uuid references auth.users(id) on delete set null,
  session_id uuid,
  surface text not null,
  provider text not null,
  role text not null check (role in ('STT','TTS','LLM','ORCHESTRATOR','TELEPHONY')),
  model text,
  -- The units each provider actually bills in. Null where not reported, never
  -- estimated into a number that looks measured.
  characters integer,
  audio_seconds numeric(10,3),
  input_tokens integer,
  output_tokens integer,
  latency_ms integer,
  -- PROVIDER when the provider reported it; CALCULATED from provider-reported
  -- units and an admin-entered rate; ESTIMATED otherwise. The label travels
  -- with the number so a dashboard cannot quietly present a guess as a fact.
  cost_basis text check (cost_basis in ('PROVIDER','CALCULATED','ESTIMATED')),
  cost_usd numeric(12,6),
  ok boolean not null default true,
  error_code text,
  provider_status integer
);

create index if not exists voice_usage_events_time on public.voice_usage_events (occurred_at desc);
create index if not exists voice_usage_events_owner on public.voice_usage_events (owner_id, occurred_at desc);

-- ── What the selector actually chose, for diagnostics ───────────────────────
--
-- Ids and categories only. Never the conversation: §P and the existing
-- privacy design both say what somebody said is theirs.

create table if not exists public.voice_keyterm_selections (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  session_id uuid,
  surface text,
  language text,
  term_ids uuid[] not null default '{}',
  categories text[] not null default '{}',
  selected_count smallint not null default 0,
  considered_count smallint not null default 0,
  max_terms smallint,
  max_chars smallint
);

create index if not exists voice_keyterm_selections_time
  on public.voice_keyterm_selections (created_at desc);

-- ── Row level security ──────────────────────────────────────────────────────
--
-- owner_id is the AUTH uid, matching comm_agents. Admin reads go through
-- users.auth_id, matching admin_settings. Both conventions already exist in
-- this database and mixing them is the defect this migration is written to
-- avoid repeating.

alter table public.voice_vocabulary_terms enable row level security;
alter table public.voice_pronunciation_rules enable row level security;
alter table public.voice_library_voices enable row level security;
alter table public.voice_personality_profiles enable row level security;
alter table public.voice_usage_events enable row level security;
alter table public.voice_keyterm_selections enable row level security;

-- The shared corpus is readable by anybody signed in and writable by nobody
-- except an admin. A tenant's own terms are theirs alone.
drop policy if exists voice_vocab_read_global on public.voice_vocabulary_terms;
create policy voice_vocab_read_global on public.voice_vocabulary_terms
  for select using (scope = 'GLOBAL' or owner_id = (select auth.uid()));

drop policy if exists voice_vocab_owner_write on public.voice_vocabulary_terms;
create policy voice_vocab_owner_write on public.voice_vocabulary_terms
  for all using (owner_id = (select auth.uid()))
  with check (owner_id = (select auth.uid()) and scope <> 'GLOBAL');

drop policy if exists voice_vocab_admin on public.voice_vocabulary_terms;
create policy voice_vocab_admin on public.voice_vocabulary_terms
  for all using (exists (
    select 1 from public.users u where u.auth_id = (select auth.uid()) and u.is_admin = true
  ));

drop policy if exists voice_pron_read on public.voice_pronunciation_rules;
create policy voice_pron_read on public.voice_pronunciation_rules
  for select using (scope = 'GLOBAL' or owner_id = (select auth.uid()));

